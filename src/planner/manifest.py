"""Manifest and checksums: ``data/<scale>/manifest.json`` (every data file + ground truth with rows, bytes and
SHA-256) and ``docs/source_manifest.md`` (provenance statement + the manifests of every scale present)."""
from __future__ import annotations

import gzip
import hashlib
import json
from pathlib import Path

from planner import __version__, tableio
from planner.config import Config, project_root
from planner.inject import GT_FILE, ground_truth_dir

LIMIT_BYTES = 50 * 1024 * 1024

PROVENANCE = (
    "All data in this repository is synthetic, produced by `python -m planner generate` from a fixed seed. "
    "No external datasets were used. Public knowledge (Indian city names, standard transport modes, ISO weeks) "
    "was used only for realism. Code license: MIT (see LICENSE)."
)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def count_rows(path: Path) -> int:
    name = path.name
    if name.endswith(".csv.gz") or name.endswith(".csv"):
        opener = gzip.open if name.endswith(".gz") else open
        with opener(path, "rb") as fh:
            return max(0, sum(1 for _ in fh) - 1)
    if name.endswith(".json"):
        with open(path, encoding="utf-8") as fh:
            return len(json.load(fh))
    if name.endswith(".sql"):
        with open(path, encoding="utf-8") as fh:
            return sum(1 for line in fh if line.startswith("("))
    return 0


def data_files(base: Path, scale: str) -> list[tuple[str, Path]]:
    root = project_root()
    files = []
    for sub in ("csv", "json", "sql"):
        d = Path(base) / sub
        if d.is_dir():
            files += sorted(p for p in d.iterdir() if p.is_file())
    gt = ground_truth_dir(scale, base) / GT_FILE
    if gt.exists():
        files.append(gt)
    out = []
    for p in files:
        try:
            rel = str(p.resolve().relative_to(root))
        except ValueError:
            rel = str(p)
        out.append((rel, p))
    return out


def build(cfg: Config, base: Path) -> dict:
    files = [{"path": rel, "rows": count_rows(p), "bytes": p.stat().st_size, "sha256": sha256(p),
              "over_50mb": p.stat().st_size > LIMIT_BYTES} for rel, p in data_files(base, cfg.scale)]
    return {"scale": cfg.scale, "seed": cfg.seed, "package_version": __version__,
            "generator_command": f"python -m planner generate --scale {cfg.scale} --seed {cfg.seed}",
            "pipeline_command": f"python -m planner run-all --scale {cfg.scale} --seed {cfg.seed}",
            "as_of_date": cfg.as_of_date.isoformat(), "provenance": PROVENANCE, "files": files}


def write(cfg: Config, base: Path) -> Path:
    m = build(cfg, base)
    p = Path(base) / "manifest.json"
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(m, fh, indent=2)
        fh.write("\n")
    return p


def write_source_manifest() -> Path:
    root = project_root()
    lines = ["# Source manifest", "", "Generated by `python -m planner export` — do not edit by hand.", "",
             "## Provenance", "", PROVENANCE, "",
             "Files over 50 MB are never committed; their row count and SHA-256 stay here so they can be regenerated "
             "and verified with the command shown.", ""]
    for scale in ("starter", "full"):
        mp = tableio.data_dir(scale) / "manifest.json"
        if not mp.exists():
            continue
        m = json.loads(mp.read_text(encoding="utf-8"))
        lines += [f"## Scale `{scale}`", "",
                  f"- Generator: `{m['generator_command']}` (seed {m['seed']}, package {m['package_version']}, "
                  f"as-of {m['as_of_date']})", f"- Full pipeline: `{m['pipeline_command']}`", "",
                  "| File | Rows | Bytes | SHA-256 |", "|---|---|---|---|"]
        for f in m["files"]:
            flag = " (over 50 MB, not committed)" if f["over_50mb"] else ""
            lines.append(f"| `{f['path']}`{flag} | {f['rows']:,} | {f['bytes']:,} | `{f['sha256']}` |")
        lines.append("")
    p = root / "docs" / "source_manifest.md"
    p.write_text("\n".join(lines), encoding="utf-8")
    return p


