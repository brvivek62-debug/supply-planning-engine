"""SQLite loading and SQL seed export, both driven by ``planner.schema`` and the written CSV text.

Values come from the deterministic CSV text (not re-formatted floats), so ``seed.sql`` is byte-stable:
integers and decimals are written as in the CSV, booleans as 1/0, text single-quoted, empty as NULL.
Tables are processed in ``schema.TABLES`` order, which is FK dependency order (parents first).
"""
from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Iterator

import pandas as pd

from planner import tableio
from planner.docs_gen import schema_sql
from planner.schema import TABLES, Table

DATA_TABLES = tuple(t.name for t in TABLES if t.name != "ground_truth")


def read_text(table: str, base: Path, fmt: str) -> pd.DataFrame:
    path = tableio.table_path(base, table, fmt)
    return pd.read_csv(path, dtype=str, keep_default_na=False, compression="gzip" if fmt == "csv.gz" else None)


def _py_values(raw: pd.DataFrame, t: Table) -> list[tuple]:
    cols = []
    for f in t.fields:
        s = raw[f.name] if f.name in raw.columns else pd.Series([""] * len(raw))
        empty = s.eq("")
        if f.dtype == "integer":
            v = pd.to_numeric(s.mask(empty)).astype("Int64").astype(object)
        elif f.dtype == "decimal":
            v = pd.to_numeric(s.mask(empty)).astype(object)
        elif f.dtype == "boolean":
            v = s.map({"true": 1, "false": 0}).astype(object)
        else:
            v = s.astype(object)
        cols.append(v.where(~empty, None).tolist())
    return list(zip(*cols)) if cols else []


def load_sqlite(base: Path, fmt: str, tables: tuple[str, ...] = DATA_TABLES) -> tuple[sqlite3.Connection, dict, list]:
    """Create the schema in memory with ``PRAGMA foreign_keys = ON`` and insert every present table in FK order.

    Returns (connection, rows loaded per table, list of (table, error) for rows SQLite rejected)."""
    con = sqlite3.connect(":memory:")
    con.executescript(schema_sql())
    con.execute("PRAGMA foreign_keys = ON")
    loaded, errors = {}, []
    by_name = {t.name: t for t in TABLES}
    for name in tables:
        if not tableio.exists(name, base, fmt):
            continue
        t = by_name[name]
        rows = _py_values(read_text(name, base, fmt), t)
        sql = f"INSERT INTO {name} ({', '.join(t.columns)}) VALUES ({', '.join('?' * len(t.columns))})"
        try:
            with con:
                con.executemany(sql, rows)
            loaded[name] = len(rows)
        except sqlite3.IntegrityError as e:   # one bad row aborts the table: retry row by row to count them
            ok = 0
            for r in rows:
                try:
                    con.execute(sql, r)
                    ok += 1
                except sqlite3.IntegrityError as e2:
                    errors.append((name, str(e2)))
            con.commit()
            loaded[name] = ok
            if not errors:
                errors.append((name, str(e)))
    return con, loaded, errors


def foreign_key_violations(con: sqlite3.Connection) -> list[tuple]:
    return con.execute("PRAGMA foreign_key_check").fetchall()


def _literal(v: str, dtype: str) -> str:
    if v == "":
        return "NULL"
    if dtype in ("integer", "decimal"):
        return v
    if dtype == "boolean":
        return "1" if v == "true" else "0"
    return "'" + v.replace("'", "''") + "'"


def seed_sql_lines(base: Path, fmt: str, tables: tuple[str, ...] = DATA_TABLES, batch: int = 500) -> Iterator[str]:
    """INSERT statements for every present table, in FK order, ``batch`` rows per statement, in one transaction."""
    by_name = {t.name: t for t in TABLES}
    yield "-- Generated by `python -m planner export` from data CSVs — do not edit by hand.\n"
    yield "-- Load after sql/schema.sql:  sqlite3 db.sqlite < sql/schema.sql && sqlite3 db.sqlite < seed.sql\n"
    yield "PRAGMA foreign_keys = ON;\nBEGIN TRANSACTION;\n"
    for name in tables:
        if not tableio.exists(name, base, fmt):
            continue
        t = by_name[name]
        raw = read_text(name, base, fmt)
        lits = [raw[f.name].map(lambda v, d=f.dtype: _literal(v, d)) for f in t.fields]
        tuples = ["(" + ", ".join(vals) + ")" for vals in zip(*lits)] if len(raw) else []
        yield f"\n-- {name}: {len(raw)} rows\n"
        head = f"INSERT INTO {name} ({', '.join(t.columns)}) VALUES\n"
        for i in range(0, len(tuples), batch):
            yield head + ",\n".join(tuples[i:i + batch]) + ";\n"
    yield "\nCOMMIT;\n"
