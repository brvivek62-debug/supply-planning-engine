"""Generate docs/data_dictionary.md, sql/schema.sql and docs/erd.md from planner.schema.

Output is deterministic (no timestamps) so regenerating never creates spurious diffs.
"""
from __future__ import annotations

from pathlib import Path

from planner import ids, schema
from planner.config import project_root
from planner.schema import TABLES, Field, Table

SQL_TYPES = {
    "string": "TEXT", "integer": "INTEGER", "decimal": "REAL", "boolean": "INTEGER",
    "date": "TEXT", "datetime": "TEXT", "week": "TEXT",
}
MERMAID_TYPES = {
    "string": "string", "integer": "int", "decimal": "decimal", "boolean": "bool",
    "date": "date", "datetime": "datetime", "week": "string",
}
KIND_TEXT = {
    schema.KIND_INPUT: "generated input (`data/<scale>/`)",
    schema.KIND_MIXED: "generated input (FIRM rows) + planner output (PLANNED rows)",
    schema.KIND_OUTPUT: "planner output (derived, never randomly generated)",
    schema.KIND_LABEL: "ground-truth label (`ground_truth/<scale>/`), never a planner input",
}


def _esc(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _allowed(f: Field) -> str:
    if f.allowed is None:
        return "—"
    if f.dtype == "boolean":
        return "true, false"
    return ", ".join(f"`{v}`" for v in f.allowed)


def _key_marks(t: Table, f: Field) -> str:
    marks = []
    if f.name in t.pk:
        marks.append("PK")
    for k in t.fks:
        if f.name in k.columns:
            ref = f"{k.ref_table}.{','.join(k.ref_columns)}"
            mark = f"FK→{ref}"
            if mark not in marks:
                marks.append(mark)
    if f.name in t.polymorphic_refs:
        marks.append("polymorphic ref")
    return "<br>".join(marks) or "—"


def _unique(t: Table, f: Field) -> str:
    if f.unique or (t.pk == (f.name,)):
        return "Yes"
    if f.name in t.pk:
        return "Part of composite PK"
    if t.natural_key and f.name in t.natural_key:
        return "Part of natural key"
    return "No"


