def _sql_literal(v: object) -> str:
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def _column_ddl(f: Field) -> str:
    parts = [f"    {f.name} {SQL_TYPES[f.dtype]}"]
    if f.required:
        parts.append("NOT NULL")
    checks = []
    if f.allowed is not None:
        checks.append(f"{f.name} IN ({', '.join(_sql_literal(v) for v in f.allowed)})")
    if f.ge is not None:
        checks.append(f"{f.name} >= {f.ge:g}")
    if f.gt is not None:
        checks.append(f"{f.name} > {f.gt:g}")
    if f.le is not None:
        checks.append(f"{f.name} <= {f.le:g}")
    if checks:
        parts.append(f"CHECK ({' AND '.join(checks)})")
    return " ".join(parts)


def schema_sql() -> str:
    out = [
        "-- Generated by `python -m planner docs` from src/planner/schema.py — do not edit by hand.",
        "-- SQLite dialect. Tables are created in dependency order; load with PRAGMA foreign_keys = ON.",
        "PRAGMA foreign_keys = ON;",
        "",
    ]
    for t in reversed(TABLES):
        out.append(f"DROP TABLE IF EXISTS {t.name};")
    out.append("")
    for t in TABLES:
        lines = [_column_ddl(f) for f in t.fields]
        lines.append(f"    PRIMARY KEY ({', '.join(t.pk)})")
        if t.natural_key:
            lines.append(f"    UNIQUE ({', '.join(t.natural_key)})")
        for k in t.fks:
            lines.append(f"    FOREIGN KEY ({', '.join(k.columns)}) REFERENCES {k.ref_table} ({', '.join(k.ref_columns)})")
        out.append(f"-- {t.description}")
        out.append(f"CREATE TABLE {t.name} (")
        out.append(",\n".join(lines))
        out.append(");")
        out.append("")
    return "\n".join(out)


