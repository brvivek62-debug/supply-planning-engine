def data_dictionary() -> str:
    out: list[str] = [
        "# Data dictionary",
        "",
        "Generated by `python -m planner docs` from `src/planner/schema.py` — do not edit by hand.",
        "",
        "## Conventions",
        "",
        "- **Types:** `string`, `integer`, `decimal`, `boolean` (`true`/`false`; `1`/`0` in SQL), "
        "`date` (ISO `YYYY-MM-DD`), `datetime` (ISO `YYYY-MM-DDTHH:MM:SS`), `week` (ISO week label `YYYYWnn`).",
        "- **Units:** quantities ending `_ea` are in base unit `EA`; money ending `_inr` is Indian rupees "
        "rounded to 2 dp; rates are 0–1 rounded to 4 dp.",
        "- **Calendar:** planning weeks are ISO weeks of 2026; 2026W01 starts 2025-12-29, which is also "
        "the as-of date of the planning run.",
        "- **Required:** `Yes` = never empty. Optional fields are empty in CSV and `NULL` in SQL.",
        "- **Rule:** the validation rule checked by `python -m planner validate`. Rules joined with `;`.",
        "- **Effective dating:** `effective_from` ≤ `effective_to`; an empty `effective_to` means open-ended.",
        "",
        "## ID patterns",
        "",
        "| ID kind | Regex | Example |",
        "|---|---|---|",
    ]
    examples = {
        "sku": ids.sku_id(1), "location": ids.location_id(1), "supplier": ids.supplier_id(1),
        "demand": ids.demand_id(ids.sku_id(1), ids.location_id(1), "2026W01"),
        "purchase_order": ids.po_id(1), "planned_order": ids.planned_order_id(1),
        "shortage": ids.shortage_id(1), "mitigation": ids.mitigation_id(ids.shortage_id(1), 1),
        "production_plan": ids.prod_plan_id(1), "exception": ids.exception_id(1),
        "lead_time": ids.lead_time_id(1), "capacity": ids.capacity_id(1), "inventory": ids.inventory_id(1),
        "txn": ids.txn_id(1), "po_event": ids.po_event_id(1), "shortage_event": ids.shortage_event_id(1),
        "bom": ids.bom_id(1), "substitute": ids.substitute_id(1), "supplier_sku": ids.supplier_sku_id(1),
        "gt": ids.gt_id(1), "week": "2026W01", "iso_week": "2025W40",
    }
    for kind, pattern in ids.PATTERNS.items():
        out.append(f"| `{kind}` | `^{_esc(pattern)}$` | `{examples[kind]}` |")

    out += ["", "## Tables", "", "| # | Table | Core entity | Group | Source | PK | Fields |", "|---|---|---|---|---|---|---|"]
    for i, t in enumerate(TABLES, 1):
        out.append(f"| {i} | [`{t.name}`](#{t.name}) | {t.core_entity or '—'} | {t.group} | {t.kind} | "
                   f"`{', '.join(t.pk)}` | {len(t.fields)} |")

    for t in TABLES:
        out += ["", f"## {t.name}", "", t.description, ""]
        meta = [
            f"- **Source:** {KIND_TEXT[t.kind]}",
            f"- **Primary key:** `{', '.join(t.pk)}`",
        ]
        if t.core_entity:
            meta.append(f"- **Core entity (brief):** {t.core_entity}")
        if t.natural_key:
            meta.append(f"- **Natural key (unique):** `{', '.join(t.natural_key)}`")
        if t.fks:
            fk_txt = "; ".join(
                f"`{','.join(k.columns)}` → `{k.ref_table}.{','.join(k.ref_columns)}`"
                f" ({k.cardinality}{', optional' if k.optional else ''})" for k in t.fks)
            meta.append(f"- **Foreign keys:** {fk_txt}")
        if t.polymorphic_refs:
            meta.append(f"- **Polymorphic references (validated in code, no SQL FK):** "
                        f"{', '.join(f'`{c}`' for c in t.polymorphic_refs)}")
        if t.effective_dated:
            meta.append("- **Effective-dated:** yes")
        if t.lifecycle:
            meta.append(f"- **Lifecycle:** `{t.lifecycle}` (see `docs/erd.md`)")
        for n in t.notes:
            meta.append(f"- {n}")
        out += meta
        out += ["", "| Field | Type | Required | Allowed values | Unit | Unique | Key | Validation rule | Description |",
                "|---|---|---|---|---|---|---|---|---|"]
        for f in t.fields:
            out.append(
                f"| `{f.name}` | {f.dtype} | {'Yes' if f.required else 'No'} | {_esc(_allowed(f))} | "
                f"{_esc(f.unit or '—')} | {_unique(t, f)} | {_esc(_key_marks(t, f))} | {_esc(f.full_rule)} | "
                f"{_esc(f.description)} |")
    out.append("")
    return "\n".join(out)


