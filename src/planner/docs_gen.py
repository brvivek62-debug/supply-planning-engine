def _mermaid_rel(k) -> str:
    """Mermaid crow's-foot notation: parent side, then child side."""
    left = "|o" if k.optional else "||"
    right = "o|" if k.cardinality == "1:0..1" else "o{"
    return f"{left}--{right}"


def erd() -> str:
    out = [
        "# Entity-relationship diagram",
        "",
        "Generated by `python -m planner docs` from `src/planner/schema.py` — do not edit by hand.",
        "",
        "Composite FKs to `sku_location` (the assortment bridge) are drawn once per child; they guarantee that "
        "demand, inventory, POs, production, PAB and shortages only exist for stocked SKU-locations.",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for t in TABLES:
        for k in t.fks:
            out.append(f"    {k.ref_table.upper()} {_mermaid_rel(k)} {t.name.upper()} : \"{k.label}\"")
    out.append("")
    for t in TABLES:
        out.append(f"    {t.name.upper()} {{")
        for f in t.fields:
            keys = []
            if f.name in t.pk:
                keys.append("PK")
            if any(f.name in k.columns for k in t.fks):
                keys.append("FK")
            if t.natural_key and f.name in t.natural_key and f.name not in t.pk:
                keys.append("UK")
            key_txt = f" {', '.join(keys)}" if keys else ""
            out.append(f"        {MERMAID_TYPES[f.dtype]} {f.name}{key_txt}")
        out.append("    }")
    out.append("```")

    out += ["", "## Cardinality", "",
            "Parent : child. `optional` = the FK column may be empty (child need not reference a parent). "
            "Every parent may have zero children unless noted.", "",
            "| Parent | Child | Via (child columns) | Cardinality | Optional |", "|---|---|---|---|---|"]
    for t in TABLES:
        for k in t.fks:
            out.append(f"| `{k.ref_table}` | `{t.name}` | `{', '.join(k.columns)}` | {k.cardinality} | "
                       f"{'yes' if k.optional else 'no'} |")
    out += ["", "### Many-to-many relationships (bridge tables)", "",
            "| Entity A | Entity B | Bridge table | Cardinality | Meaning |", "|---|---|---|---|---|"]
    for a, b, bridge, meaning in schema.MANY_TO_MANY:
        out.append(f"| `{a}` | `{b}` | `{bridge}` | N:M | {meaning} |")
    out += ["", "### One-to-one relationships", "",
            "| Entity A | Entity B | Rule |", "|---|---|---|",
            "| `purchase_order` (shipped, open) | `inventory` (IN_TRANSIT row) | 1:0..1 — at most one IN_TRANSIT "
            "row per PO; a second row is the DUPLICATE_INBOUND anomaly. |",
            "| `shortage` | `mitigation_option` (is_recommended) | 1:0..1 — at most one recommended option per shortage. |"]

    out += ["", "### Polymorphic references", "",
            "These columns point at different tables depending on a type column, so they are validated in code "
            "instead of by an SQL FK.", "", "| Table.column | Type column | Targets |", "|---|---|---|",
            "| `shortage_cause.evidence_id` | `evidence_type` | " + ", ".join(f"`{e}`" for e in schema.EVIDENCE_TYPES) + " |",
            "| `exception.record_id` | `entity` | `inventory`, `purchase_order`, `mitigation_option` |",
            "| `ground_truth.record_id` | `entity` | any input table |"]

    out += ["", "## Effective-dated entities", "", "| Table | Columns |", "|---|---|"]
    for t in TABLES:
        if t.effective_dated:
            cols = [c for c in ("effective_from", "effective_to") if c in t.columns]
            out.append(f"| `{t.name}` | {', '.join(f'`{c}`' for c in cols)} |")

    out += ["", "## Lifecycle state machines", ""]
    for lc in schema.LIFECYCLES.values():
        out += [f"### {lc.name} (`{lc.entity}`)", "", lc.description, ""]
        if lc.event_table:
            out += [f"History is kept append-only in `{lc.event_table}`.", ""]
        out += ["```mermaid", "stateDiagram-v2"]
        for s in lc.initial:
            out.append(f"    [*] --> {s}")
        for a, b in lc.transitions:
            out.append(f"    {a} --> {b}")
        for s in lc.terminal:
            out.append(f"    {s} --> [*]")
        out += ["```", "", "| From | To |", "|---|---|"]
        for s in lc.initial:
            out.append(f"| (start) | `{s}` |")
        for a, b in lc.transitions:
            out.append(f"| `{a}` | `{b}` |")
        out.append("")
    return "\n".join(out)


