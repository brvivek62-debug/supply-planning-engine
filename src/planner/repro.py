"""Reproducibility check: generate + plan twice with the same seed and once with seed + 1 into temporary folders,
then compare row counts and SHA-256 of every data file and the ground truth -> ``reports/reproducibility.md``."""
from __future__ import annotations

import json
import tempfile
import time
from pathlib import Path

from planner import generate, plan, tableio
from planner.config import Config, load_config
from planner.manifest import count_rows, sha256


def _run(cfg: Config, out: Path) -> dict[str, tuple[int, str]]:
    generate.run(cfg, out)
    plan.run(cfg, out)
    files = sorted((out / "csv").iterdir()) + [out / "ground_truth" / "ground_truth.csv"]
    return {f"{p.parent.name}/{p.name}": (count_rows(p), sha256(p)) for p in files}


def run(cfg: Config, out_dir: Path | None = None) -> dict:
    t0 = time.perf_counter()
    other = load_config(cfg.scale, cfg.seed + 1)
    with tempfile.TemporaryDirectory(prefix="planner-repro-") as tmp:
        a = _run(cfg, Path(tmp) / "run1")
        b = _run(cfg, Path(tmp) / "run2")
        c = _run(other, Path(tmp) / "run3")
    names = sorted(set(a) | set(b))
    rows = [{"file": n, "rows_1": a.get(n, (None, ""))[0], "rows_2": b.get(n, (None, ""))[0],
             "sha_1": a.get(n, (0, ""))[1], "sha_2": b.get(n, (0, ""))[1],
             "match": a.get(n) == b.get(n), "differs_other_seed": c.get(n, (0, ""))[1] != a.get(n, (0, ""))[1]}
            for n in names]
    res = {"scale": cfg.scale, "seed": cfg.seed, "other_seed": other.seed, "files": len(rows),
           "identical": all(r["match"] for r in rows),
           "files_changed_by_other_seed": sum(r["differs_other_seed"] for r in rows),
           "seconds": round(time.perf_counter() - t0, 1), "rows": rows}
    folder = Path(out_dir) if out_dir else tableio.reports_dir(cfg.scale)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "reproducibility.md").write_text(render(res), encoding="utf-8")
    with open(folder / "reproducibility.json", "w", encoding="utf-8", newline="\n") as fh:
        json.dump({k: v for k, v in res.items() if k != "seconds"}, fh, indent=2)
        fh.write("\n")
    return res


def render(r: dict) -> str:
    lines = [f"# Reproducibility — scale `{r['scale']}`", "",
             f"Generated by `python -m planner repro-check --scale {r['scale']} --seed {r['seed']}`: `generate` + `plan` "
             f"run twice with seed {r['seed']} into fresh temporary folders, and once with seed {r['other_seed']}.", "",
             f"- Same seed: **{'all ' + str(r['files']) + ' files byte-identical' if r['identical'] else 'MISMATCH'}**",
             f"- Seed {r['other_seed']}: {r['files_changed_by_other_seed']} of {r['files']} files have a different SHA-256 "
             "(files that do not depend on random draws, e.g. location calendars, may legitimately match)", "",
             "| File | Rows (run 1) | Rows (run 2) | SHA-256 (run 1) | SHA-256 (run 2) | Match | Differs with other seed |",
             "|---|---|---|---|---|---|---|"]
    for x in r["rows"]:
        lines.append(f"| `{x['file']}` | {x['rows_1']:,} | {x['rows_2']:,} | `{x['sha_1'][:16]}…` | `{x['sha_2'][:16]}…` | "
                     f"{'yes' if x['match'] else 'NO'} | {'yes' if x['differs_other_seed'] else 'no'} |")
    lines.append("")
    return "\n".join(lines)
